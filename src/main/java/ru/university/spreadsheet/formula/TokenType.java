package ru.university.spreadsheet.formula;

/**
 * Вид лексемы формулы.
 */
public enum TokenType {

    /** Число, например 12 или 3.5. */
    NUMBER,

    /** Ссылка на ячейку, например A1. */
    REF,

    /** Имя функции или неизвестное имя. */
    FUNC,

    /** Оператор: сложение, вычитание, умножение, деление, степень, остаток или сравнение. */
    OP,

    /** Открывающая скобка. */
    LPAREN,

    /** Закрывающая скобка. */
    RPAREN,

    /** Разделитель аргументов: запятая или точка с запятой. */
    COMMA,

    /** Двоеточие — разделитель границ диапазона. */
    COLON,

    /** Конец формулы. */
    EOF
}
