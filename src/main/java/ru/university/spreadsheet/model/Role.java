package ru.university.spreadsheet.model;

/**
 * Роль пользователя, определяющая набор доступных ему операций.
 */
public enum Role {

    /** Обычный пользователь: работает только со своими документами. */
    USER,

    /** Администратор: дополнительно управляет учётными записями и видит все документы. */
    ADMIN
}
